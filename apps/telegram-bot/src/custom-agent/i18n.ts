const catalogs: Record<CustomLocale, Catalog> = { en, "zh-Hans": zhHans, ru };

export function resolveCustomLocale(code?: string | null): CustomLocale {
  const raw = (code ?? "").trim().toLowerCase().replace(/_/g, "-");
  if (raw.startsWith("zh")) return "zh-Hans";
  if (raw.startsWith("ru")) return "ru";
  return "en";
}

export function ct(locale: CustomLocale, key: string, params?: Record<string, string | number>): string {
  const catalog = catalogs[locale] ?? catalogs.en;
  let template = catalog[key] ?? catalogs.en[key] ?? key;
  if (params) {
    template = template.replace(/\{\{(\w+)\}\}/g, (_, k: string) =>
      params[k] === undefined || params[k] === null ? `{{${k}}}` : String(params[k]),
    );
  }
  return template;
}

export function customCommandDescriptions(locale: CustomLocale): { command: string; description: string }[] {
  return [
    { command: "start", description: ct(locale, "cmd.start") },
    { command: "custom", description: ct(locale, "cmd.custom") },
    { command: "orders", description: ct(locale, "cmd.orders") },
    { command: "language", description: ct(locale, "cmd.language") },
    { command: "help", description: ct(locale, "cmd.help") },
  ];
}

export function formatMoney(cents: number, currency: string): string {
  const amount = (cents / 100).toFixed(2);
  return `${currency.toUpperCase()} ${amount}`;
}
